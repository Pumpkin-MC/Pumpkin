/// Which room piece a child renders as; indices point into the parent's room
/// arena.
#[derive(Clone, Copy)]
enum ChildKind {
    /// `OceanMonumentEntryRoom` (OMP l.1072-1103).
    Entry { room: usize },
    /// `OceanMonumentCoreRoom` (OMP l.385-456); its layout is fixed, so no
    /// room data is needed at render time.
    Core,
    /// `OceanMonumentDoubleXYRoom` (OMP l.554-650).
    DoubleXy { room: usize },
    /// `OceanMonumentDoubleYZRoom` (OMP l.458-552).
    DoubleYz { room: usize },
    /// `OceanMonumentDoubleZRoom` (OMP l.652-731).
    DoubleZ { room: usize },
    /// `OceanMonumentDoubleXRoom` (OMP l.733-793).
    DoubleX { room: usize },
    /// `OceanMonumentDoubleYRoom` (OMP l.795-867).
    DoubleY { room: usize },
    /// `OceanMonumentSimpleTopRoom` (OMP l.869-915).
    SimpleTop { room: usize },
    /// `OceanMonumentSimpleRoom` (OMP l.917-1070) with its ctor-drawn design.
    Simple { room: usize, main_design: i32 },
    /// `OceanMonumentWingRoom` (OMP l.288-383); `mainDesign = randomValue & 1`
    /// (l.294).
    Wing { main_design: i32 },
    /// `OceanMonumentPenthouse` (OMP l.237-286).
    Penthouse,
}

struct ChildPiece {
    piece: StructurePiece,
    kind: ChildKind,
}

/// `OceanMonumentPiece.makeBoundingBox(orientation, roomDefinition, w, h, d)`
/// (OMP l.1623-1647): positions a room piece inside the monument-local grid
/// (cells are 8 x 4 x 8 blocks).
fn room_bounding_box(
    orientation: BlockDirection,
    grid_index: i32,
    room_width: i32,
    room_height: i32,
    room_depth: i32,
) -> BlockBox {
    let room_x = grid_index % 5;
    let room_z = grid_index / 5 % 5;
    let room_y = grid_index / 25;
    // `StructurePiece.makeBoundingBox` (StructurePiece.java l.68-73) is
    // `BlockBox::create_box`.
    let mut bounding_box = BlockBox::create_box(
        0,
        0,
        0,
        horizontal_axis(orientation),
        room_width * 8,
        room_height * 4,
        room_depth * 8,
    );
    match orientation {
        BlockDirection::North => {
            bounding_box.move_pos(room_x * 8, room_y * 4, -(room_z + room_depth) * 8 + 1);
        }
        BlockDirection::South => bounding_box.move_pos(room_x * 8, room_y * 4, room_z * 8),
        BlockDirection::West => {
            bounding_box.move_pos(-(room_z + room_depth) * 8 + 1, room_y * 4, room_x * 8);
        }
        // EAST is the `default` arm in vanilla (l.1642-1644).
        _ => bounding_box.move_pos(room_z * 8, room_y * 4, room_x * 8),
    }
    bounding_box
}

/// Room piece constructor shared by every grid-room child (OMP l.1617-1621):
/// generation depth 1 and the monument-wide orientation.
fn new_child(
    piece_type: StructurePieceType,
    orientation: BlockDirection,
    grid_index: i32,
    spans: (i32, i32, i32),
    kind: ChildKind,
) -> ChildPiece {
    let mut piece = StructurePiece::new(
        piece_type,
        room_bounding_box(orientation, grid_index, spans.0, spans.1, spans.2),
        1,
    );
    piece.set_facing(Some(orientation));
    ChildPiece { piece, kind }
}

/// `OceanMonumentWingRoom` ctor (OMP l.292-295).
fn wing_child(orientation: BlockDirection, bounding_box: BlockBox, main_design: i32) -> ChildPiece {
    let mut piece = StructurePiece::new(StructurePieceType::OceanMonumentWingRoom, bounding_box, 1);
    piece.set_facing(Some(orientation));
    ChildPiece {
        piece,
        kind: ChildKind::Wing { main_design },
    }
}

/// `FitDoubleXYRoom.fits` (OMP l.71-78).
fn fits_double_xy(rooms: &[Room], room: usize) -> bool {
    if rooms[room].has_opening[EAST]
        && !rooms[connection(rooms, room, EAST)].claimed
        && rooms[room].has_opening[UP]
        && !rooms[connection(rooms, room, UP)].claimed
    {
        let east = connection(rooms, room, EAST);
        rooms[east].has_opening[UP] && !rooms[connection(rooms, east, UP)].claimed
    } else {
        false
    }
}

/// `FitDoubleYZRoom.fits` (OMP l.47-54).
fn fits_double_yz(rooms: &[Room], room: usize) -> bool {
    if rooms[room].has_opening[NORTH]
        && !rooms[connection(rooms, room, NORTH)].claimed
        && rooms[room].has_opening[UP]
        && !rooms[connection(rooms, room, UP)].claimed
    {
        let north = connection(rooms, room, NORTH);
        rooms[north].has_opening[UP] && !rooms[connection(rooms, north, UP)].claimed
    } else {
        false
    }
}

/// `FitDoubleZRoom.fits` (OMP l.95-98).
fn fits_double_z(rooms: &[Room], room: usize) -> bool {
    rooms[room].has_opening[NORTH] && !rooms[connection(rooms, room, NORTH)].claimed
}

/// `FitDoubleXRoom.fits` (OMP l.117-120).
fn fits_double_x(rooms: &[Room], room: usize) -> bool {
    rooms[room].has_opening[EAST] && !rooms[connection(rooms, room, EAST)].claimed
}

/// `FitDoubleYRoom.fits` (OMP l.135-138).
fn fits_double_y(rooms: &[Room], room: usize) -> bool {
    rooms[room].has_opening[UP] && !rooms[connection(rooms, room, UP)].claimed
}

/// `FitSimpleTopRoom.fits` (OMP l.153-156).
fn fits_simple_top(rooms: &[Room], room: usize) -> bool {
    !rooms[room].has_opening[WEST]
        && !rooms[room].has_opening[EAST]
        && !rooms[room].has_opening[NORTH]
        && !rooms[room].has_opening[SOUTH]
        && !rooms[room].has_opening[UP]
}

/// Applies the seven vanilla room fitters in registration order
/// (OMP l.1124-1137), claiming rooms exactly like each fitter's `create`.
/// Only `FitSimpleRoom.create` draws a random value.
#[allow(clippy::too_many_lines)] // Direct vanilla transcription.
fn fit_room(
    rooms: &mut [Room],
    room: usize,
    orientation: BlockDirection,
    random: &mut RandomGenerator,
) -> ChildPiece {
    if fits_double_xy(rooms, room) {
        // `FitDoubleXYRoom.create` (OMP l.80-87).
        let east = connection(rooms, room, EAST);
        let up = connection(rooms, room, UP);
        let east_up = connection(rooms, east, UP);
        rooms[room].claimed = true;
        rooms[east].claimed = true;
        rooms[up].claimed = true;
        rooms[east_up].claimed = true;
        new_child(
            StructurePieceType::OceanMonumentDoubleXYRoom,
            orientation,
            rooms[room].index,
            (2, 2, 1),
            ChildKind::DoubleXy { room },
        )
    } else if fits_double_yz(rooms, room) {
        // `FitDoubleYZRoom.create` (OMP l.56-63).
        let north = connection(rooms, room, NORTH);
        let up = connection(rooms, room, UP);
        let north_up = connection(rooms, north, UP);
        rooms[room].claimed = true;
        rooms[north].claimed = true;
        rooms[up].claimed = true;
        rooms[north_up].claimed = true;
        new_child(
            StructurePieceType::OceanMonumentDoubleYZRoom,
            orientation,
            rooms[room].index,
            (1, 2, 2),
            ChildKind::DoubleYz { room },
        )
    } else if fits_double_z(rooms, room) {
        // `FitDoubleZRoom.create` (OMP l.100-109): vanilla re-checks the
        // north opening and falls back to the south neighbour; the fits()
        // gate (l.95-98) makes the fallback unreachable, but it is
        // transcribed for fidelity.
        let source =
            if rooms[room].has_opening[NORTH] && !rooms[connection(rooms, room, NORTH)].claimed {
                room
            } else {
                connection(rooms, room, SOUTH)
            };
        let north = connection(rooms, source, NORTH);
        rooms[source].claimed = true;
        rooms[north].claimed = true;
        new_child(
            StructurePieceType::OceanMonumentDoubleZRoom,
            orientation,
            rooms[source].index,
            (1, 1, 2),
            ChildKind::DoubleZ { room: source },
        )
    } else if fits_double_x(rooms, room) {
        // `FitDoubleXRoom.create` (OMP l.122-127).
        let east = connection(rooms, room, EAST);
        rooms[room].claimed = true;
        rooms[east].claimed = true;
        new_child(
            StructurePieceType::OceanMonumentDoubleXRoom,
            orientation,
            rooms[room].index,
            (2, 1, 1),
            ChildKind::DoubleX { room },
        )
    } else if fits_double_y(rooms, room) {
        // `FitDoubleYRoom.create` (OMP l.140-145).
        let up = connection(rooms, room, UP);
        rooms[room].claimed = true;
        rooms[up].claimed = true;
        new_child(
            StructurePieceType::OceanMonumentDoubleYRoom,
            orientation,
            rooms[room].index,
            (1, 2, 1),
            ChildKind::DoubleY { room },
        )
    } else if fits_simple_top(rooms, room) {
        // `FitSimpleTopRoom.create` (OMP l.158-162).
        rooms[room].claimed = true;
        new_child(
            StructurePieceType::OceanMonumentSimpleTopRoom,
            orientation,
            rooms[room].index,
            (1, 1, 1),
            ChildKind::SimpleTop { room },
        )
    } else {
        // `FitSimpleRoom` (OMP l.165-180) always fits; the room ctor draws
        // the interior design with one nextInt(3) (OMP l.923).
        rooms[room].claimed = true;
        let main_design = random.next_bounded_i32(3);
        new_child(
            StructurePieceType::OceanMonumentSimpleRoom,
            orientation,
            rooms[room].index,
            (1, 1, 1),
            ChildKind::Simple { room, main_design },
        )
    }
}

/// `BoundingBox.fromCorners`: the component-wise min/max of two corners.
fn box_from_corners(a: Vector3<i32>, b: Vector3<i32>) -> BlockBox {
    BlockBox::new(
        a.x.min(b.x),
        a.y.min(b.y),
        a.z.min(b.z),
        a.x.max(b.x),
        a.y.max(b.y),
        a.z.max(b.z),
    )
}

