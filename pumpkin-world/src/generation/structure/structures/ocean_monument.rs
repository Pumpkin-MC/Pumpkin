#[cfg(test)]
mod tests {
    use super::*;
    use crate::generation::structure::structures::create_chunk_random;

    fn context() -> StructureGeneratorContext<'static> {
        StructureGeneratorContext {
            seed: 20260727,
            chunk_x: 12,
            chunk_z: -7,
            random: create_chunk_random(20260727, 12, -7),
            sea_level: 63,
            min_y: -64,
            max_y: 319,
            height_sampler: None,
            structure_key: None,
        }
    }

    #[test]
    fn monument_is_one_building_piece_with_children() {
        let position = OceanMonumentGenerator
            .get_structure_position(context())
            .expect("monument always produces a position");
        let collector = position.collector.lock().unwrap();
        assert_eq!(collector.pieces.len(), 1);
        let building = collector.pieces[0]
            .as_any()
            .downcast_ref::<OceanMonumentPiece>()
            .expect("piece is the monument building");
        // OMP l.1117: constant 58x23x58 box starting at y=39.
        let bb = building.piece.bounding_box;
        assert_eq!(bb.max.x - bb.min.x + 1, 58);
        assert_eq!(bb.max.z - bb.min.z + 1, 58);
        assert_eq!(bb.min.y, 39);
        assert_eq!(bb.max.y, 61);
        // Entry, core, wings and penthouse always exist (OMP l.1121-1149).
        assert!(building.children.len() >= 5);
        // Every child stays inside the building footprint.
        for child in &building.children {
            let cb = child.piece.bounding_box;
            assert!(cb.min.x >= bb.min.x && cb.max.x <= bb.max.x);
            assert!(cb.min.z >= bb.min.z && cb.max.z <= bb.max.z);
            assert!(cb.min.y >= bb.min.y && cb.max.y <= bb.max.y);
        }
    }

    #[test]
    fn every_grid_room_is_claimed_after_fitting() {
        let position = OceanMonumentGenerator
            .get_structure_position(context())
            .expect("monument always produces a position");
        let collector = position.collector.lock().unwrap();
        let building = collector.pieces[0]
            .as_any()
            .downcast_ref::<OceanMonumentPiece>()
            .expect("piece is the monument building");
        // FitSimpleRoom always fits (OMP l.170-173), so after the ctor loop
        // no room can remain unclaimed.
        assert!(building.rooms.iter().all(|room| room.claimed));
    }
}
