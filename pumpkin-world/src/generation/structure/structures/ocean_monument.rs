/// Placement helpers bound to one piece (the building or a child room):
/// vanilla's `OceanMonumentPiece` base-class methods.
struct MonumentOps<'a> {
    piece: &'a StructurePiece,
    sea_level: i32,
}

impl MonumentOps<'_> {
    /// `StructurePiece.placeBlock` (StructurePiece.java l.156-178); ocean
    /// monument pieces keep the default `canBeReplaced` (always true). All
    /// monument palette blocks are symmetric full cubes, so the mirror /
    /// rotation transform inside `add_block` is an identity.
    fn place_block(
        &self,
        chunk: &mut ProtoChunk,
        state: &'static BlockState,
        x: i32,
        y: i32,
        z: i32,
        chunk_box: &BlockBox,
    ) {
        self.piece.add_block(chunk, state, x, y, z, chunk_box);
    }

    /// `StructurePiece.generateBox` (StructurePiece.java l.211-224). Every
    /// ocean monument call passes skipAir=false and the SAME state for the
    /// edge and fill blocks (verified across all of OMP), so a single state
    /// argument is used; the corners are `(x, y, z)` triples so that the
    /// hundreds of transcribed call sites stay one vanilla line each.
    fn generate_box(
        &self,
        chunk: &mut ProtoChunk,
        chunk_box: &BlockBox,
        (x0, y0, z0): (i32, i32, i32),
        (x1, y1, z1): (i32, i32, i32),
        state: &'static BlockState,
    ) {
        self.piece.fill_with_outline(
            chunk, chunk_box, false, x0, y0, z0, x1, y1, z1, state, state,
        );
    }

    /// `OceanMonumentPiece.generateWaterBox` (OMP l.1657-1671): floods a box
    /// with water (or air above sea level), never replacing ice variants or
    /// existing water (`FILL_KEEP`, l.1590).
    fn generate_water_box(
        &self,
        chunk: &mut ProtoChunk,
        chunk_box: &BlockBox,
        (x0, y0, z0): (i32, i32, i32),
        (x1, y1, z1): (i32, i32, i32),
    ) {
        for y in y0..=y1 {
            for x in x0..=x1 {
                for z in z0..=z1 {
                    let state_id = self.piece.get_block_at(chunk, x, y, z, chunk_box).id;
                    if is_fill_keep(Block::from_state_id(state_id)) {
                        continue;
                    }
                    // l.1663: above sea level the opening becomes air. The
                    // `block != FILL_BLOCK` guard is subsumed by FILL_KEEP
                    // (which contains the water block) but kept for fidelity.
                    if self.piece.apply_y_transform(y) >= self.sea_level
                        && state_id != fill_block().id
                    {
                        self.place_block(chunk, Block::AIR.default_state, x, y, z, chunk_box);
                    } else {
                        self.place_block(chunk, fill_block(), x, y, z, chunk_box);
                    }
                }
            }
        }
    }

    /// `OceanMonumentPiece.generateBoxOnFillOnly` (OMP l.1688-1697): only
    /// replaces still-water source blocks (state identity with `FILL_BLOCK`).
    fn generate_box_on_fill_only(
        &self,
        chunk: &mut ProtoChunk,
        chunk_box: &BlockBox,
        (x0, y0, z0): (i32, i32, i32),
        (x1, y1, z1): (i32, i32, i32),
        target: &'static BlockState,
    ) {
        for y in y0..=y1 {
            for x in x0..=x1 {
                for z in z0..=z1 {
                    if self.piece.get_block_at(chunk, x, y, z, chunk_box).id != fill_block().id {
                        continue;
                    }
                    self.place_block(chunk, target, x, y, z, chunk_box);
                }
            }
        }
    }

    /// `OceanMonumentPiece.generateDefaultFloor` (OMP l.1673-1686): an 8x8
    /// gray floor tile, optionally pierced by a bordered 2x2 opening.
    fn generate_default_floor(
        &self,
        chunk: &mut ProtoChunk,
        chunk_box: &BlockBox,
        x_off: i32,
        z_off: i32,
        down_opening: bool,
    ) {
        if down_opening {
            // l.1675-1682.
            self.generate_box(
                chunk,
                chunk_box,
                (x_off, 0, z_off),
                (x_off + 2, 0, z_off + 8 - 1),
                base_gray(),
            );
            self.generate_box(
                chunk,
                chunk_box,
                (x_off + 5, 0, z_off),
                (x_off + 8 - 1, 0, z_off + 8 - 1),
                base_gray(),
            );
            self.generate_box(
                chunk,
                chunk_box,
                (x_off + 3, 0, z_off),
                (x_off + 4, 0, z_off + 2),
                base_gray(),
            );
            self.generate_box(
                chunk,
                chunk_box,
                (x_off + 3, 0, z_off + 5),
                (x_off + 4, 0, z_off + 8 - 1),
                base_gray(),
            );
            self.generate_box(
                chunk,
                chunk_box,
                (x_off + 3, 0, z_off + 2),
                (x_off + 4, 0, z_off + 2),
                base_light(),
            );
            self.generate_box(
                chunk,
                chunk_box,
                (x_off + 3, 0, z_off + 5),
                (x_off + 4, 0, z_off + 5),
                base_light(),
            );
            self.generate_box(
                chunk,
                chunk_box,
                (x_off + 2, 0, z_off + 3),
                (x_off + 2, 0, z_off + 4),
                base_light(),
            );
            self.generate_box(
                chunk,
                chunk_box,
                (x_off + 5, 0, z_off + 3),
                (x_off + 5, 0, z_off + 4),
                base_light(),
            );
        } else {
            // l.1684.
            self.generate_box(
                chunk,
                chunk_box,
                (x_off, 0, z_off),
                (x_off + 8 - 1, 0, z_off + 8 - 1),
                base_gray(),
            );
        }
    }

    /// `OceanMonumentPiece.chunkIntersects` (OMP l.1699-1705): does the given
    /// local XZ rectangle, transformed to world space, touch this chunk?
    fn chunk_intersects(&self, chunk_box: &BlockBox, x0: i32, z0: i32, x1: i32, z1: i32) -> bool {
        let wx0 = self.piece.apply_x_transform(x0, z0);
        let wz0 = self.piece.apply_z_transform(x0, z0);
        let wx1 = self.piece.apply_x_transform(x1, z1);
        let wz1 = self.piece.apply_z_transform(x1, z1);
        chunk_box.intersects_raw_xz(wx0.min(wx1), wz0.min(wz1), wx0.max(wx1), wz0.max(wz1))
    }

    /// `StructurePiece.fillColumnDown` (StructurePiece.java l.286-295).
    fn fill_column_down(
        &self,
        chunk: &mut ProtoChunk,
        state: &'static BlockState,
        x: i32,
        y: i32,
        z: i32,
        chunk_box: &BlockBox,
    ) {
        self.piece.fill_downwards(chunk, state, x, y, z, chunk_box);
    }

    /// `OceanMonumentPiece.spawnElder` (OMP l.1707-1716): vanilla creates an
    /// `ELDER_GUARDIAN`, heals it to full (its fresh-spawn default), snaps it
    /// to the block center with zero rotation and adds it to the world when
    /// the position is inside the current chunk. Pumpkin queues the entity
    /// NBT on the proto chunk instead (the same worldgen entity queue used by
    /// mineshaft chest minecarts); the entity loader restores health to the
    /// attribute maximum when no `Health` tag is present, matching the heal.
    /// `finalizeSpawn` only touches the entity's own RNG, never the worldgen
    /// random, so no draws are skipped here.
    fn spawn_elder(&self, chunk: &mut ProtoChunk, chunk_box: &BlockBox, x: i32, y: i32, z: i32) {
        let pos = self.piece.offset_pos(x, y, z);
        if !chunk_box.contains_pos(&pos) {
            return;
        }
        let mut nbt = NbtCompound::new();
        nbt.put_string("id", "minecraft:elder_guardian".to_string());
        // l.1712: snapTo(x + 0.5, y, z + 0.5, 0.0, 0.0).
        nbt.put_list(
            "Pos",
            vec![
                NbtTag::Double(f64::from(pos.x) + 0.5),
                NbtTag::Double(f64::from(pos.y)),
                NbtTag::Double(f64::from(pos.z) + 0.5),
            ],
        );
        nbt.put_list(
            "Motion",
            vec![
                NbtTag::Double(0.0),
                NbtTag::Double(0.0),
                NbtTag::Double(0.0),
            ],
        );
        nbt.put_list("Rotation", vec![NbtTag::Float(0.0), NbtTag::Float(0.0)]);
        chunk.add_entity(nbt);
    }
}

