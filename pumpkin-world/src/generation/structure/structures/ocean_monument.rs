//! Vanilla 26.2 ocean monument generation.
//!
//! Ported from:
//! - `net/minecraft/world/level/levelgen/structure/structures/OceanMonumentStructure.java` (OMS)
//! - `net/minecraft/world/level/levelgen/structure/structures/OceanMonumentPieces.java` (OMP)
//!
//! Line numbers in comments refer to the decompiled vanilla sources above.
//! Random draws are performed in exactly the vanilla order so the room graph,
//! the wing designs, and the per-chunk decoration are seed-compatible.
//!
//! Known gaps versus vanilla (missing facilities, not invented behavior):
//! - OMS l.40-46: vanilla rejects a monument unless EVERY biome within a
//!   29-block radius of the chunk center (sampled at sea level) is in
//!   `#minecraft:required_ocean_monument_surrounding`. Pumpkin's
//!   `StructureGeneratorContext` exposes no biome source, so only the
//!   framework's single-point `structure.biomes` check (performed by
//!   `try_generate_structure` / `lazily_generate_structure` on the start
//!   position) applies. Monuments may therefore generate slightly closer to
//!   ocean edges than vanilla allows.
//! - OMS l.61-77 (`regeneratePiecesAfterLoad`): vanilla rebuilds the child
//!   piece list when a legacy structure start is loaded from NBT. Pumpkin
//!   never serializes piece lists (structure starts are recomputed from the
//!   world seed), so there is nothing to regenerate; behavior is equivalent
//!   for worlds generated by Pumpkin itself.
//! - OMS l.47 (`onTopOfChunkCenter` with `Heightmap.Types.OCEAN_FLOOR_WG`):
//!   the start position's Y is vanilla's first occupied ocean-floor height at
//!   the chunk center. At structure-position time Pumpkin has no chunk to
//!   query, so the surface height estimator (which tracks the noise terrain
//!   surface, i.e. the seabed in oceans) is used, falling back to sea level.
//!   The block layout is unaffected: the building's Y span is the constant
//!   39..=61 (OMP l.1117, l.1111).
//! - `WorldGenLevel.getSeaLevel()` (OMP l.1256, l.1663) has no equivalent on
//!   `ProtoChunk` at placement time, so the generator's sea level is captured
//!   from `StructureGeneratorContext` when the start is created. Both values
//!   are the same dimension constant in vanilla.

