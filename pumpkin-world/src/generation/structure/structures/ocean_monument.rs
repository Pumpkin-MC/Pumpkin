pub struct OceanMonumentGenerator;

impl StructureGenerator for OceanMonumentGenerator {
    fn get_structure_position(
        &self,
        context: StructureGeneratorContext<'_>,
    ) -> Option<StructurePosition> {
        let mut random = context.random;
        // `createTopPiece` (OMS l.50-55): the building corner sits 29 blocks
        // west/north of the chunk corner, and one nextInt(4) picks the
        // orientation from `Direction.Plane.HORIZONTAL`.
        let west = start_block_x(context.chunk_x) - 29;
        let north = start_block_z(context.chunk_z) - 29;
        let orientation = HORIZONTAL_FACES[as_index(random.next_bounded_i32(4))];
        let building =
            OceanMonumentPiece::new(&mut random, west, north, orientation, context.sea_level);

        // `onTopOfChunkCenter` (OMS l.47): position at the chunk center, on
        // the OCEAN_FLOOR_WG height (see the module-level gap note).
        let center_x = get_center_x(context.chunk_x);
        let center_z = get_center_z(context.chunk_z);
        let start_y = context.height_sampler.map_or(context.sea_level, |sampler| {
            sampler.estimate_height(center_x, center_z)
        });

        let mut collector = StructurePiecesCollector::default();
        collector.add_piece(Box::new(building));
        Some(StructurePosition {
            start_pos: BlockPos::new(center_x, start_y, center_z),
            collector: Arc::new(collector.into()),
        })
    }
}

