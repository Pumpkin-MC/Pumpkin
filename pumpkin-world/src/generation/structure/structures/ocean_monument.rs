/// `OceanMonumentPieces.RoomDefinition` (OMP l.188-235), flattened into an
/// arena: `connections` stores indices into the room vector.
struct Room {
    /// Packed grid index, or 1001/1002/1003 for the special rooms.
    index: i32,
    connections: [Option<usize>; 6],
    has_opening: [bool; 6],
    claimed: bool,
    is_source: bool,
    scan_index: i32,
}

impl Room {
    /// OMP l.196-198.
    const fn new(index: i32) -> Self {
        Self {
            index,
            connections: [None; 6],
            has_opening: [false; 6],
            claimed: false,
            is_source: false,
            scan_index: 0,
        }
    }

    /// `updateOpenings` (OMP l.205-209).
    fn update_openings(&mut self) {
        for direction in 0..6 {
            self.has_opening[direction] = self.connections[direction].is_some();
        }
    }

    /// `countOpenings` (OMP l.227-234).
    fn count_openings(&self) -> usize {
        self.has_opening.iter().filter(|&&open| open).count()
    }
}

/// `setConnection` (OMP l.200-203): links both rooms symmetrically.
fn set_connection(rooms: &mut [Room], from: usize, direction: usize, to: usize) {
    rooms[from].connections[direction] = Some(to);
    rooms[to].connections[opposite(direction)] = Some(from);
}

/// The connected room in a direction; callers only use this where vanilla
/// dereferences the connection unconditionally.
fn connection(rooms: &[Room], room: usize, direction: usize) -> usize {
    rooms[room].connections[direction].expect("room connection exists")
}

/// `findSource` (OMP l.211-221): depth-first search towards the source room
/// along open connections, marking visited rooms with `scan_index`.
fn find_source(rooms: &mut [Room], room: usize, scan_index: i32) -> bool {
    if rooms[room].is_source {
        return true;
    }
    rooms[room].scan_index = scan_index;
    for direction in 0..6 {
        let Some(connected) = rooms[room].connections[direction] else {
            continue;
        };
        if rooms[room].has_opening[direction]
            && rooms[connected].scan_index != scan_index
            && find_source(rooms, connected, scan_index)
        {
            return true;
        }
    }
    false
}

/// `Util.shuffle` (Util.java l.1035-1041): Fisher-Yates from the back; one
/// `nextInt(i)` per element with `i` counting down from the length to 2.
fn vanilla_shuffle<T>(list: &mut [T], random: &mut RandomGenerator) {
    let mut i = i32::try_from(list.len()).expect("room list length fits in i32");
    while i > 1 {
        let swap_to = random.next_bounded_i32(i);
        list.swap(as_index(i - 1), as_index(swap_to));
        i -= 1;
    }
}

/// Allocates a grid room (OMP l.1165-1166 pattern).
fn alloc_room(grid: &mut [Option<usize>; 75], rooms: &mut Vec<Room>, pos: i32) {
    rooms.push(Room::new(pos));
    grid[as_index(pos)] = Some(rooms.len() - 1);
}

/// Result of `generateRoomGraph`.
struct RoomGraph {
    rooms: Vec<Room>,
    /// Iteration order of the returned vanilla list: all grid rooms in
    /// ascending grid-index order, shuffled, followed by the roof and both
    /// wing placeholders (OMP l.1223-1250).
    ordered: Vec<usize>,
    source: usize,
    core: usize,
}

/// `MonumentBuilding.generateRoomGraph` (OMP l.1156-1252). Random draws, in
/// order: one `nextInt(4)` for the core-room column, the `Util.shuffle`
/// draws, then up to `5` `nextInt(6)` draws per room in the closing loop.
#[expect(clippy::too_many_lines)] // Direct vanilla transcription.
fn generate_room_graph(random: &mut RandomGenerator) -> RoomGraph {
    let mut rooms: Vec<Room> = Vec::new();
    let mut grid: [Option<usize>; 75] = [None; 75];
    // l.1162-1168: floor 0 rooms, 5 x 4.
    for x in 0..5 {
        for z in 0..4 {
            alloc_room(&mut grid, &mut rooms, room_index(x, 0, z));
        }
    }
    // l.1169-1175: floor 1 rooms, 5 x 4.
    for x in 0..5 {
        for z in 0..4 {
            alloc_room(&mut grid, &mut rooms, room_index(x, 1, z));
        }
    }
    // l.1176-1182: floor 2 rooms, 3 x 2.
    for x in 1..4 {
        for z in 0..2 {
            alloc_room(&mut grid, &mut rooms, room_index(x, 2, z));
        }
    }
    // l.1183.
    let source = grid[as_index(GRIDROOM_SOURCE_INDEX)].expect("source grid room exists");
    // l.1184-1203: connect neighbouring rooms. For a Z-stepping direction the
    // connection is stored under the OPPOSITE index (l.1195-1199), so
    // `connections[NORTH]` points at the +z neighbour: the room graph's
    // "north" faces the back of the monument.
    for x in 0..5i32 {
        for z in 0..5i32 {
            for y in 0..3i32 {
                let pos = room_index(x, y, z);
                let Some(room) = grid[as_index(pos)] else {
                    continue;
                };
                for (direction, step) in DIRECTION_STEPS.iter().enumerate() {
                    let neigh_x = x + step.0;
                    let neigh_y = y + step.1;
                    let neigh_z = z + step.2;
                    if !(0..5).contains(&neigh_x)
                        || !(0..5).contains(&neigh_z)
                        || !(0..3).contains(&neigh_y)
                    {
                        continue;
                    }
                    let Some(neighbor) = grid[as_index(room_index(neigh_x, neigh_y, neigh_z))]
                    else {
                        continue;
                    };
                    if neigh_z == z {
                        set_connection(&mut rooms, room, direction, neighbor);
                    } else {
                        set_connection(&mut rooms, room, opposite(direction), neighbor);
                    }
                }
            }
        }
    }
    // l.1204-1212: roof and wing placeholder rooms.
    let roof = rooms.len();
    rooms.push(Room::new(PENTHOUSE_INDEX));
    let left_wing = rooms.len();
    rooms.push(Room::new(LEFTWING_INDEX));
    let right_wing = rooms.len();
    rooms.push(Room::new(RIGHTWING_INDEX));
    let top_connect = grid[as_index(GRIDROOM_TOP_CONNECT_INDEX)].expect("top connect room exists");
    set_connection(&mut rooms, top_connect, UP, roof);
    let left_connect =
        grid[as_index(GRIDROOM_LEFTWING_CONNECT_INDEX)].expect("left wing connect room exists");
    set_connection(&mut rooms, left_connect, SOUTH, left_wing);
    let right_connect =
        grid[as_index(GRIDROOM_RIGHTWING_CONNECT_INDEX)].expect("right wing connect room exists");
    set_connection(&mut rooms, right_connect, SOUTH, right_wing);
    rooms[roof].claimed = true;
    rooms[left_wing].claimed = true;
    rooms[right_wing].claimed = true;
    rooms[source].is_source = true;
    // l.1214-1222: pick the 2x2x2 core-room block (one nextInt(4)) and claim
    // the core, its east/north neighbours, and the four rooms above them.
    let core = grid[as_index(room_index(random.next_bounded_i32(4), 0, 2))]
        .expect("core grid room exists");
    let core_east = connection(&rooms, core, EAST);
    let core_north = connection(&rooms, core, NORTH);
    let core_east_north = connection(&rooms, core_east, NORTH);
    rooms[core].claimed = true;
    rooms[core_east].claimed = true;
    rooms[core_north].claimed = true;
    rooms[core_east_north].claimed = true;
    for lower in [core, core_east, core_north, core_east_north] {
        let above = connection(&rooms, lower, UP);
        rooms[above].claimed = true;
    }
    // l.1223-1229: collect all grid rooms in grid-index order and refresh
    // their opening flags. The wing placeholders keep all-false openings
    // (vanilla only calls updateOpenings on grid rooms and the roof), which
    // makes their single doorway impossible to seal in the loop below.
    let mut ordered: Vec<usize> = Vec::new();
    for slot in grid {
        if let Some(room) = slot {
            rooms[room].update_openings();
            ordered.push(room);
        }
    }
    rooms[roof].update_openings();
    // l.1230: Util.shuffle.
    vanilla_shuffle(&mut ordered, random);
    // l.1231-1247: try to seal up to two openings per room (at most five
    // attempts), keeping every room connected to the source.
    let mut scan_index = 1;
    for &room in &ordered {
        let mut close_count = 0;
        let mut attempts = 0;
        while close_count < 2 && attempts < 5 {
            attempts += 1;
            let direction = as_index(random.next_bounded_i32(6));
            if !rooms[room].has_opening[direction] {
                continue;
            }
            let connected = connection(&rooms, room, direction);
            let opposite_direction = opposite(direction);
            rooms[room].has_opening[direction] = false;
            rooms[connected].has_opening[opposite_direction] = false;
            // l.1240: Java `&&` short-circuits, so the second findSource (and
            // its scanIndex increment) only runs when the first succeeds.
            let mut reachable = find_source(&mut rooms, room, scan_index);
            scan_index += 1;
            if reachable {
                reachable = find_source(&mut rooms, connected, scan_index);
                scan_index += 1;
            }
            if reachable {
                close_count += 1;
            } else {
                rooms[room].has_opening[direction] = true;
                rooms[connected].has_opening[opposite_direction] = true;
            }
        }
    }
    // l.1248-1250.
    ordered.push(roof);
    ordered.push(left_wing);
    ordered.push(right_wing);
    RoomGraph {
        rooms,
        ordered,
        source,
        core,
    }
}

