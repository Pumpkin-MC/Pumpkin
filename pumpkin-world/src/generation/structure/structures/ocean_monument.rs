/// `MonumentBuilding` (OMP l.1105-1579). Vanilla registers the building as
/// the single structure piece and renders its child rooms from inside
/// `postProcess`; the children here live in `children`, in vanilla creation
/// order.
pub struct OceanMonumentPiece {
    piece: StructurePiece,
    sea_level: i32,
    rooms: Vec<Room>,
    children: Vec<ChildPiece>,
}

impl OceanMonumentPiece {
    /// `MonumentBuilding` constructor (OMP l.1116-1150): builds the room
    /// graph, claims the entry and core rooms, fits the remaining rooms with
    /// the seven fitters in registration order, moves every room piece by the
    /// world position of grid origin (9, 0, 22), and finally appends the two
    /// wings and the penthouse.
    fn new(
        random: &mut RandomGenerator,
        west: i32,
        north: i32,
        orientation: BlockDirection,
        sea_level: i32,
    ) -> Self {
        // OMP l.1117: makeBoundingBox(west, 39, north, direction, 58, 23, 58)
        // spans y 39..=61 (TOP_POSITION, l.1111).
        let mut piece = StructurePiece::new(
            StructurePieceType::OceanMonumentBase,
            BlockBox::create_box(west, 39, north, horizontal_axis(orientation), 58, 23, 58),
            0,
        );
        piece.set_facing(Some(orientation));

        // OMP l.1119: generateRoomGraph.
        let RoomGraph {
            mut rooms,
            ordered,
            source,
            core,
        } = generate_room_graph(random);
        // l.1120-1122: the entry and core rooms come first.
        rooms[source].claimed = true;
        let mut children = vec![
            new_child(
                StructurePieceType::OceanMonumentEntryRoom,
                orientation,
                rooms[source].index,
                (1, 1, 1),
                ChildKind::Entry { room: source },
            ),
            new_child(
                StructurePieceType::OceanMonumentCoreRoom,
                orientation,
                rooms[core].index,
                (2, 2, 2),
                ChildKind::Core,
            ),
        ];
        // l.1123-1138: fit every remaining unclaimed grid room.
        for &room in &ordered {
            if rooms[room].claimed || is_special(rooms[room].index) {
                continue;
            }
            children.push(fit_room(&mut rooms, room, orientation, random));
        }
        // l.1139-1142: shift the room pieces from grid space into world
        // space by the world position of grid origin (9, 0, 22).
        let offset = piece.offset_pos(9, 0, 22);
        for child in &mut children {
            child
                .piece
                .bounding_box
                .move_pos(offset.x, offset.y, offset.z);
        }
        // l.1143-1145: wing and penthouse boxes are built in world space and
        // are NOT moved by the offset above.
        let left_wing_box =
            box_from_corners(piece.offset_pos(1, 1, 1), piece.offset_pos(23, 8, 21));
        let right_wing_box =
            box_from_corners(piece.offset_pos(34, 1, 1), piece.offset_pos(56, 8, 21));
        let penthouse_box =
            box_from_corners(piece.offset_pos(22, 13, 22), piece.offset_pos(35, 17, 35));
        // l.1146-1149: one full nextInt() seeds both wing designs; the Java
        // post-increment gives the second wing the opposite parity (the wing
        // ctor keeps `randomValue & 1`, l.294).
        let wing_random = random.next_i32();
        children.push(wing_child(orientation, left_wing_box, wing_random & 1));
        children.push(wing_child(
            orientation,
            right_wing_box,
            wing_random.wrapping_add(1) & 1,
        ));
        let mut penthouse =
            StructurePiece::new(StructurePieceType::OceanMonumentPenthouse, penthouse_box, 1);
        penthouse.set_facing(Some(orientation));
        children.push(ChildPiece {
            piece: penthouse,
            kind: ChildKind::Penthouse,
        });

        Self {
            piece,
            sea_level,
            rooms,
            children,
        }
    }

    /// The connected room in a direction (never absent where used; see
    /// `connection`).
    fn connected(&self, room: usize, direction: usize) -> usize {
        connection(&self.rooms, room, direction)
    }

    /// Renders one child piece, mirroring the per-class `postProcess`
    /// dispatch of OMP l.1293-1296.
    fn place_child(
        &self,
        index: usize,
        chunk: &mut ProtoChunk,
        random: &mut RandomGenerator,
        chunk_box: &BlockBox,
    ) {
        let child = &self.children[index];
        let ops = MonumentOps {
            piece: &child.piece,
            sea_level: self.sea_level,
        };
        match child.kind {
            ChildKind::Entry { room } => self.place_entry_room(&ops, chunk, chunk_box, room),
            ChildKind::Core => ops.place_core_room(chunk, chunk_box),
            ChildKind::DoubleXy { room } => self.place_double_xy_room(&ops, chunk, chunk_box, room),
            ChildKind::DoubleYz { room } => self.place_double_yz_room(&ops, chunk, chunk_box, room),
            ChildKind::DoubleZ { room } => self.place_double_z_room(&ops, chunk, chunk_box, room),
            ChildKind::DoubleX { room } => self.place_double_x_room(&ops, chunk, chunk_box, room),
            ChildKind::DoubleY { room } => self.place_double_y_room(&ops, chunk, chunk_box, room),
            ChildKind::SimpleTop { room } => {
                self.place_simple_top_room(&ops, chunk, random, chunk_box, room);
            }
            ChildKind::Simple { room, main_design } => {
                self.place_simple_room(&ops, chunk, random, chunk_box, room, main_design);
            }
            ChildKind::Wing { main_design } => {
                ops.place_wing_room(chunk, chunk_box, main_design);
            }
            ChildKind::Penthouse => ops.place_penthouse(chunk, chunk_box),
        }
    }

    /// `MonumentBuilding.postProcess` (OMP l.1255-1292), excluding the child
    /// loop (l.1293-1296) which runs in `place`. Draws no random values.
    fn place_building(&self, chunk: &mut ProtoChunk, chunk_box: &BlockBox) {
        let ops = MonumentOps {
            piece: &self.piece,
            sea_level: self.sea_level,
        };
        // l.1256-1257: flood the footprint up to max(seaLevel, 64), relative
        // to the box bottom at y=39.
        let water_height = self.sea_level.max(64) - self.piece.bounding_box.min.y;
        ops.generate_water_box(chunk, chunk_box, (0, 0, 0), (58, water_height, 58));
        // l.1258-1265.
        ops.generate_wing(chunk, chunk_box, false, 0);
        ops.generate_wing(chunk, chunk_box, true, 33);
        ops.generate_entrance_archs(chunk, chunk_box);
        ops.generate_entrance_wall(chunk, chunk_box);
        ops.generate_roof_piece(chunk, chunk_box);
        ops.generate_lower_wall(chunk, chunk_box);
        ops.generate_middle_wall(chunk, chunk_box);
        ops.generate_upper_wall(chunk, chunk_box);
        // l.1266-1286: 4x4 foundation pillars on a 9-block lattice around the
        // rim (the middle of the front edge is skipped).
        let mut pillar_x = 0;
        while pillar_x < 7 {
            let mut pillar_z = 0;
            while pillar_z < 7 {
                if pillar_z == 0 && pillar_x == 3 {
                    pillar_z = 6;
                }
                let base_x = pillar_x * 9;
                let base_z = pillar_z * 9;
                for w in 0..4 {
                    for d in 0..4 {
                        ops.place_block(chunk, base_light(), base_x + w, 0, base_z + d, chunk_box);
                        ops.fill_column_down(
                            chunk,
                            base_light(),
                            base_x + w,
                            -1,
                            base_z + d,
                            chunk_box,
                        );
                    }
                }
                if pillar_x == 0 || pillar_x == 6 {
                    pillar_z += 1;
                } else {
                    pillar_z += 6;
                }
            }
            pillar_x += 1;
        }
        // l.1287-1292: carve a stepped water skirt around the platform.
        for i in 0..5 {
            ops.generate_water_box(
                chunk,
                chunk_box,
                (-1 - i, i * 2, -1 - i),
                (-1 - i, 23, 58 + i),
            );
            ops.generate_water_box(
                chunk,
                chunk_box,
                (58 + i, i * 2, -1 - i),
                (58 + i, 23, 58 + i),
            );
            ops.generate_water_box(chunk, chunk_box, (-i, i * 2, -1 - i), (57 + i, 23, -1 - i));
            ops.generate_water_box(chunk, chunk_box, (-i, i * 2, 58 + i), (57 + i, 23, 58 + i));
        }
    }
}

impl StructurePieceBase for OceanMonumentPiece {
    fn as_any(&self) -> &dyn std::any::Any {
        self
    }

    fn get_structure_piece(&self) -> &StructurePiece {
        &self.piece
    }

    fn get_structure_piece_mut(&mut self) -> &mut StructurePiece {
        &mut self.piece
    }

    /// The child boxes live in world space, so they shift with the building
    /// (the monument is never actually shifted, but `translate` must stay
    /// consistent).
    fn translate(&mut self, x: i32, y: i32, z: i32) {
        self.piece.translate(x, y, z);
        for child in &mut self.children {
            child.piece.bounding_box.move_pos(x, y, z);
        }
    }

    fn place(
        &mut self,
        chunk: &mut ProtoChunk,
        _block_registry: &dyn WorldPortalExt,
        random: &mut RandomGenerator,
        _seed: i64,
        chunk_box: &BlockBox,
    ) {
        self.place_building(chunk, chunk_box);
        // OMP l.1293-1296: children render in creation order, but only those
        // intersecting the current chunk. That intersection test also gates
        // their random draws, exactly as in vanilla.
        for index in 0..self.children.len() {
            if !self.children[index]
                .piece
                .bounding_box
                .intersects(chunk_box)
            {
                continue;
            }
            self.place_child(index, chunk, random, chunk_box);
        }
    }
}

