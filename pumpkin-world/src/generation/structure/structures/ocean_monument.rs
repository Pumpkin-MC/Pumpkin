/// `getRoomIndex` (OMP l.1608-1610): the grid is 5 wide (x), 5 deep (z) and
/// 3 floors tall (y); an index packs to `y * 25 + z * 5 + x`.
const fn room_index(x: i32, y: i32, z: i32) -> i32 {
    y * 25 + z * 5 + x
}

/// `GRIDROOM_SOURCE_INDEX` (OMP l.1599): the entry room at grid (2, 0, 0).
const GRIDROOM_SOURCE_INDEX: i32 = room_index(2, 0, 0);
/// `GRIDROOM_TOP_CONNECT_INDEX` (OMP l.1600): grid (2, 2, 0).
const GRIDROOM_TOP_CONNECT_INDEX: i32 = room_index(2, 2, 0);
/// `GRIDROOM_LEFTWING_CONNECT_INDEX` (OMP l.1601): grid (0, 1, 0).
const GRIDROOM_LEFTWING_CONNECT_INDEX: i32 = room_index(0, 1, 0);
/// `GRIDROOM_RIGHTWING_CONNECT_INDEX` (OMP l.1602): grid (4, 1, 0).
const GRIDROOM_RIGHTWING_CONNECT_INDEX: i32 = room_index(4, 1, 0);
/// `LEFTWING_INDEX` (OMP l.1603).
const LEFTWING_INDEX: i32 = 1001;
/// `RIGHTWING_INDEX` (OMP l.1604).
const RIGHTWING_INDEX: i32 = 1002;
/// `PENTHOUSE_INDEX` (OMP l.1605).
const PENTHOUSE_INDEX: i32 = 1003;

/// `RoomDefinition.isSpecial` (OMP l.223-225): the roof and wing placeholder
/// rooms carry indices outside the 75-slot grid.
const fn is_special(index: i32) -> bool {
    index >= 75
}

/// Converts a known-non-negative Java `int` (a grid index or a bounded random
/// result) to `usize`.
fn as_index(value: i32) -> usize {
    usize::try_from(value).expect("value is non-negative")
}

