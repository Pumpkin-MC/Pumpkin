//! The event kinds the host can dispatch, one line per `get-`/`set-` pair of the WIT `event`
//! resource
//!
//! Each line names the record, the matching [`EventType`](super::EventType) case and the two
//! resource methods.
//!
//! Lines are split based on how the generated `set-` method takes its record (by reference or by value).
//!
//! - Pass by reference: occurs when it holds heap data (strings, lists) and no resource handles. and
//!
//! - Pass by value: covers records with a player or entity as well as plain `Copy` ones.
//!
//! If a record changes in a way that flips this, the compiler reports a mismatch on its line and the
//! line needs to swap sections.

