pub(super) async fn build_stone_floor(
    helper: &GameTestHelper,
    width: i32,
    depth: i32,
) -> GameTestResult<()> {
    for x in 0..width {
        for z in 0..depth {
            helper
                .set_block_default(&BlockPos::new(x, 0, z), &Block::STONE)
                .await?;
        }
    }
    Ok(())
}
