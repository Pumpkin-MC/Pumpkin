use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
};

pub fn build() -> String {
    let items: BTreeMap<String, serde_json::Value> =
        serde_json::from_str(&fs::read_to_string("../../assets/items.json").unwrap()).unwrap();
    let blocks: serde_json::Value =
        serde_json::from_str(&fs::read_to_string("../../assets/blocks.json").unwrap()).unwrap();
    let item_keys: BTreeSet<_> = items.keys().map(|key| qualify(key)).collect();
    let block_keys: BTreeSet<_> = blocks["blocks"]
        .as_array()
        .unwrap()
        .iter()
        .map(|block| qualify(block["name"].as_str().unwrap()))
        .collect();
    let mut code = "// Generated by pumpkin-codegen -- sdk. Do not edit.\n\n".to_string();
    for (name, keys) in [("ITEM_KEYS", item_keys), ("BLOCK_KEYS", block_keys)] {
        code.push_str(&format!("pub const {name}: &[&str] = &[\n"));
        for key in keys {
            code.push_str(&format!("    {key:?},\n"));
        }
        code.push_str("];\n\n");
    }
    code
}

fn qualify(key: &str) -> String {
    if key.contains(':') {
        key.to_string()
    } else {
        format!("minecraft:{key}")
    }
}
